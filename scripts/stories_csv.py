"""Every test's story in one place: docs/TEST-STORIES.md to read, and
docs/TEST-STORIES.csv for a spreadsheet.

Each test file starts with a header (STORY/OUTCOME/PROVES/WHY, or
GUARD/CATCHES/IF REMOVED/PROVES for a developer tripwire). This script reads
those headers and writes them as one CSV, one row per test file, so the
founder can review every story in a spreadsheet instead of across many
Markdown files. The test file stays the source; the CSV is generated.

docs/TEST-STORIES.md (founder 2026-11-09: "show me the evals in the docs
and tests in a form of user stories in one doc") reads the same headers as
a page, then every golden eval set (tests/evals/golden/*.jsonl): what each
surface is graded on and each row's case, so the tests and the evals are
read in one place.

  python scripts/stories_csv.py           # rewrite docs/TEST-STORIES.csv
  python scripts/stories_csv.py --check   # exit 1 if the CSV is stale or a test has no header

tests/test_stories_csv.py runs --check in CI.
"""

from __future__ import annotations

import ast
import csv
import io
import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
OUT = REPO / "docs" / "TEST-STORIES.csv"
PAGE = REPO / "docs" / "TEST-STORIES.md"
GOLDEN = REPO / "tests" / "evals" / "golden"
COLUMNS = ["file", "type", "story", "outcomes", "proves", "why"]
SECTIONS = ("STORY", "GUARD", "OUTCOME", "CATCHES", "IF REMOVED", "PROVES", "WHY")
_SECTION = re.compile(r"^\s*(" + "|".join(SECTIONS) + r")\b\s*(.*)$")


def story_files() -> list[Path]:
    files = [p for p in (REPO / "tests").rglob("test_*.py") if "__pycache__" not in p.parts]
    root = REPO / "test_jwks.py"
    if root.exists():
        files.append(root)
    return sorted(files, key=lambda p: p.relative_to(REPO).as_posix())


def parse_header(text: str) -> dict[str, str] | None:
    """The header's sections, or None when the file has no STORY/GUARD header."""
    sections: dict[str, list[str]] = {}
    current = None
    for line in text.splitlines():
        m = _SECTION.match(line)
        if m:
            current = m.group(1)
            sections[current] = [m.group(2)] if m.group(2) else []
        elif current:
            sections[current].append(line.strip())

    def joined(name: str, sep: str) -> str:
        return sep.join(x for x in sections.get(name, []) if x).strip()

    if "STORY" in sections:
        return {"type": "Story", "story": joined("STORY", " "), "outcomes": joined("OUTCOME", "\n"),
                "proves": joined("PROVES", "\n"), "why": joined("WHY", " ")}
    if "GUARD" in sections:
        why = joined("IF REMOVED", " ")
        return {"type": "Guard", "story": joined("GUARD", " "), "outcomes": joined("CATCHES", "\n"),
                "proves": joined("PROVES", "\n"), "why": f"If removed: {why}" if why else ""}
    return None


def rows() -> tuple[list[dict[str, str]], list[str]]:
    found, missing = [], []
    for path in story_files():
        rel = path.relative_to(REPO).as_posix()
        try:
            doc = ast.get_docstring(ast.parse(path.read_text(encoding="utf-8"))) or ""
        except SyntaxError:
            doc = ""
        header = parse_header(doc)
        if header is None:
            missing.append(rel)
            continue
        found.append({"file": rel, **header})
    return found, missing


def render(found: list[dict[str, str]]) -> str:
    buf = io.StringIO()
    writer = csv.DictWriter(buf, fieldnames=COLUMNS, lineterminator="\n")
    writer.writeheader()
    writer.writerows(found)
    return buf.getvalue()


def evals() -> list[dict]:
    """Each golden eval set: its surface, its header lines, its rows."""
    import json
    sets = []
    for path in sorted(GOLDEN.glob("*.jsonl")):
        notes, cases = [], []
        for line in path.read_text(encoding="utf-8").splitlines():
            line = line.strip()
            if line.startswith("//"):
                notes.append(line.lstrip("/").strip())
            elif line:
                try:
                    cases.append(json.loads(line))
                except ValueError:
                    continue
        sets.append({"surface": path.stem, "file": path.relative_to(REPO).as_posix(),
                     "notes": notes, "cases": cases})
    return sets


def _cell(text: str) -> str:
    return " ".join(str(text or "").split()).replace("|", "\\|")


def render_page(found: list[dict[str, str]], sets: list[dict]) -> str:
    """The stories and the evals as one page. Generated: edit the test
    files' headers and the golden sets, then run this script."""
    out = ["# Test stories and evals", "",
           "Generated by `python scripts/stories_csv.py` from every test file's header and every",
           "golden eval set. Do not edit by hand: change the test or the eval, then run the script.",
           "", f"**{len(found)} test files** (part 1) and **{len(sets)} eval sets, "
           f"{sum(len(s['cases']) for s in sets)} cases** (part 2).", "",
           "## Part 1 · Tests as user stories", ""]
    for row in found:
        out += [f"### {row['story'] or row['file']}", "",
                f"`{row['file']}` · {row['type']}", ""]
        for line in (row["outcomes"] or "").splitlines():
            line = line.strip()
            if not line:
                continue
            if re.match(r"^(O\d+|C\d+)\b", line):
                out.append(f"- **{line.split()[0]}** {line[len(line.split()[0]):].strip()}")
            elif out and out[-1].startswith("- "):
                out[-1] += " " + line
            else:
                out.append(f"- {line}")
        if row["why"]:
            out += ["", f"*Why:* {_cell(row['why'])}"]
        out.append("")
    out += ["## Part 2 · Evals: what the AI's words are graded on", "",
            "Each set grades one AI surface: the production prompt and its checks run on every case,",
            "the rules first (no digits, length, banned words), then a model grades the meaning.", ""]
    for s in sets:
        out += [f"### {s['surface']}", "", f"`{s['file']}` · {len(s['cases'])} cases", ""]
        out += [f"> {_cell(n)}" for n in s["notes"]]
        if s["notes"]:
            out.append("")
        out += ["| Case | What it checks | Graded on |", "|---|---|---|"]
        for case in s["cases"]:
            rubric = case.get("rubric") or {}
            graded = rubric.get("semantic_intent") or ", ".join(sorted(rubric)) or ""
            out.append(f"| {_cell(case.get('id'))} | {_cell(case.get('description'))} | {_cell(graded)} |")
        out.append("")
    return "\n".join(out).rstrip() + "\n"


def main(argv: list[str]) -> int:
    found, missing = rows()
    text = render(found)
    page = render_page(found, evals())
    if "--check" in argv:
        problems = [f"no STORY or GUARD header: {m}" for m in missing]
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != text:
            problems.append("docs/TEST-STORIES.csv is out of date: run python scripts/stories_csv.py")
        if not PAGE.exists() or PAGE.read_text(encoding="utf-8") != page:
            problems.append("docs/TEST-STORIES.md is out of date: run python scripts/stories_csv.py")
        for p in problems:
            print(p)
        return 1 if problems else 0
    OUT.write_text(text, encoding="utf-8")
    PAGE.write_text(page, encoding="utf-8")
    print(f"wrote {OUT.relative_to(REPO)} and {PAGE.relative_to(REPO)}: {len(found)} test files")
    for m in missing:
        print(f"no STORY or GUARD header: {m}")
    return 1 if missing else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
